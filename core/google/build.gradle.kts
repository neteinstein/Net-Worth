import java.util.Properties

plugins {
    alias(libs.plugins.networth.kmp.library)
    alias(libs.plugins.kotlin.serialization)
}

/*
 * Google OAuth client IDs are configuration, not secrets, but they differ per developer/Cloud project,
 * so they come from (in order) Gradle properties, the git-ignored local.properties, or environment
 * variables, and are compiled into GoogleConfig. Missing values compile to "" and the app shows a
 * "Google sign-in is not configured" message instead of crashing. See docs/google-cloud-setup.md.
 */
val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
}

fun googleSetting(key: String): String = providers.gradleProperty("networth.google.$key").orNull
    ?: localProperties.getProperty("networth.google.$key")
    ?: providers.environmentVariable("NETWORTH_GOOGLE_" + key.replace(Regex("([A-Z])"), "_$1").uppercase()).orNull
    ?: ""

val googleSettings = mapOf(
    "WEB_CLIENT_ID" to googleSetting("webClientId"),
    "IOS_CLIENT_ID" to googleSetting("iosClientId"),
    "API_KEY" to googleSetting("apiKey"),
    "PROJECT_NUMBER" to googleSetting("projectNumber"),
)

val generateGoogleConfig = tasks.register("generateGoogleConfig") {
    val outputDir = layout.buildDirectory.dir("generated/googleConfig/kotlin")
    val fields = googleSettings.entries.joinToString("\n") { (name, value) ->
        "    const val $name: String = \"${value.replace("\\", "\\\\").replace("\"", "\\\"")}\""
    }
    val source = """
        |// Generated by :core:google:generateGoogleConfig — do not edit.
        |package com.neteinstein.networth.core.google.config
        |
        |object GoogleConfig {
        |$fields
        |}
        |
    """.trimMargin()
    inputs.property("source", source)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("com/neteinstein/networth/core/google/config/GoogleConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(source)
    }
}

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(generateGoogleConfig)
            dependencies {
                implementation(projects.core.domain)
                api(libs.ktor.client.core)
                implementation(libs.kotlinx.serialization.json)
            }
        }
        androidMain.dependencies {
            implementation(libs.ktor.client.okhttp)
            implementation(libs.androidx.activity)
            implementation(libs.androidx.credentials)
            implementation(libs.androidx.credentials.play.services.auth)
            implementation(libs.googleid)
