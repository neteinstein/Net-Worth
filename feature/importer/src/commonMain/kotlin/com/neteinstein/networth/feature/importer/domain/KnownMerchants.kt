    /** Number of brand patterns known (for tests and the "knows N merchants" line). */
    val size: Int get() = patterns.size

    private fun List<String>.containsRun(run: List<String>): Boolean {
        if (run.size > size) return false
        for (start in 0..size - run.size) {
            if (run.indices.all { this[start + it] == run[it] }) return true
        }
        return false
    }

    /** Uppercase words without accents; "&" stays inside words ("H&M"), apostrophes join ("Levi's" → "LEVIS"). */
    internal fun words(text: String): List<String> =
        text.uppercase().map { accents[it] ?: it }.joinToString("").replace("'", "").replace("’", "")
            .split(Regex("[^A-Z0-9&]+")).filter { it.isNotEmpty() && it != "&" }
