    /** Pattern words → subcategory, longest first so the most specific brand wins. */
    private val patterns: List<Pair<List<String>, String>> =
        bySubcategory.flatMap { (subcategory, brands) -> brands.map { words(it) to subcategory } }
            .filter { it.first.isNotEmpty() }
            .sortedByDescending { (words) -> words.sumOf { it.length } + words.size }

    /** The default subcategory name ("Supermarket") for a movement's merchant, if it is a known brand. */
    fun subcategoryFor(info: DescriptionInfo): String? {
        // "Pagamento (de) Baixo Valor Cartão": unnamed low-value card payments go to Other (Outros) › Misc.
        if (info.kind == MovementKind.LOW_VALUE_CARD) return "Misc"
        val name = info.merchant ?: info.counterparty ?: return null
        val text = words(name)
        if (text.isEmpty()) return null
        return patterns.firstOrNull { (pattern) -> text.containsRun(pattern) }?.second
    }

